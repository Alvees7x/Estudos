# Operadores aritméticos

#Adição: +
#Subtração: -
#Multiplicação: *
#Divisão: /
#Divisão inteira: //
#Exponenciação: **
#Módulo: % = resto da divisão
#Igualdade: ==

# Comparação: !=, >, <, >=, <=

#Exemplos:
a = 10
b = 5
c = a + b  # Adição
d = a - b  # Subtração
e = a * b  # Multiplicação
f = a / b  # Divisão
g = a // b  # Divisão inteira
h = a ** b  # Exponenciação
i = a % b  # Módulo
j = a == b  # Igualdade
k = a != b  # Comparação
l = a > b   # Maior que
m = a < b   # Menor que
n = a >= b  # Maior ou igual
o = a <= b  # Menor ou igual

print(f'A soma de {a} e {b} é igual a {c}')
print(f'A subtração de {a} e {b} é igual a {d}')
print(f'A multiplicação de {a} e {b} é igual a {e}')
print(f'A divisão de {a} e {b} é igual a {f}')
print(f'A divisão inteira de {a} e {b} é igual a {g}')
print(f'A exponenciação de {a} e {b} é igual a {h}')
print(f'O módulo de {a} e {b} é igual a {i}')
print(f'A igualdade de {a} e {b} é {j}')
print(f'A comparação de {a} e {b} é {k}')
print(f'{a} é maior que {b}? {l}')
print(f'{a} é menor que {b}? {m}')
print(f'{a} é maior ou igual a {b}? {n}')
print(f'{a} é menor ou igual a {b}? {o}')